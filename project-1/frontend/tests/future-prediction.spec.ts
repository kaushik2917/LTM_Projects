test("timestamp cutoff drives graph and persisted prediction request", async ({ page, request }) => {
  await page.goto("/graph");
  const slider = page.getByRole("slider", { name: "Temporal cutoff" });
  await expect(slider).toBeVisible();
  const responsePromise = page.waitForResponse(r => r.url().includes("/analysis?cutoff_timestamp=") && r.url().includes("10%3A04%3A00"));
  await slider.focus(); await slider.press("Home");
  for (let i = 0; i < 4; i++) await slider.press("ArrowRight");
  const response = await responsePromise;
  const analysis = await response.json();
  expect(analysis.evidence.map((e: { evidence_id: string }) => e.evidence_id)).toEqual(["EV-00001", "EV-00002", "EV-00003", "EV-00004"]);
  expect(analysis.future_prediction.supporting_evidence_ids).toEqual(["EV-00001", "EV-00002", "EV-00003", "EV-00004"]);
  expect(analysis.synthetic_prediction.status).toBe("not_available");
  await expect(page.locator("tbody tr")).toHaveCount(4);
  const endpoint = new URL("/api/workflow/INC-00001/prediction", response.url()).toString();
  const result = await request.post(endpoint, { data: { cutoff_timestamp: "2026-09-25T10:04:00" } });
  expect(result.ok()).toBe(true);
  const prediction = await result.json();
  expect(prediction.status).toBe("available");
  expect(prediction.prediction_mode).toBe("synthetic_temporal_model");
  expect(prediction.predictions.reduce((sum: number, p: { probability: number }) => sum + p.probability, 0)).toBeCloseTo(1);
  const probabilities = Object.values(prediction.probability_distribution) as number[];
  const entropy = -probabilities.filter(p => p > 0).reduce((sum, p) => sum + p * Math.log(p), 0) / Math.log(probabilities.length);
  expect(prediction.uncertainty).toBeCloseTo(entropy, 12);
  expect(prediction.observed_future_outcome).toBeNull();
  expect(prediction.prediction_correctness).toBeNull();
  expect(prediction.prediction_id).toBeTruthy();
  await slider.press("End");
  await expect(page.locator("tbody tr")).toHaveCount(6);
  await expect(page.getByLabel("Future attack prediction")).toContainText("EV-00006");
});

